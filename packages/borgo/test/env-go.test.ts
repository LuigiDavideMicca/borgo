import { describe, expect, setDefaultTimeout, test } from "bun:test";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, statSync, utimesSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { defineEnv, ENV_META, type EnvMeta } from "../src/env";
import { goEnvSource, serverSpecs, writeGoEnv } from "../src/env-go";

setDefaultTimeout(180_000);

const repo = join(import.meta.dir, "..", "..", "..").replaceAll("\\", "/");

const schema = {
  server: {
    DB_PATH: { default: "app.db" },
    TIMEOUT_MS: { type: "number", default: 30_000 },
    RATIO: { type: "number", default: 0.5 },
    DEBUG: { type: "boolean", optional: true },
    VERBOSE: { type: "boolean", default: false },
    SMTP_PORT: { type: "port", default: 587 },
    DATABASE_URL: { type: "url" },
    SECRET: { optional: true, validate: (raw: string) => raw },
    TOKEN: { validate: (raw: string) => raw, default: "dev-token" },
    NAME: { optional: true },
    LEVEL: { optional: true, default: "info" },
    DOUBLED: { type: "number", optional: true, validate: (raw: string) => Number(raw) * 2 },
    // what go source cannot hold as written: a byte order mark, and -0
    MARKED: { default: "a" + String.fromCharCode(0xfeff) + "b" },
    NEG_ZERO: { type: "number", default: -0 },
  },
  client: { BORGO_PUBLIC_TITLE: { default: "t" } },
} as const;

const metaOf = (env: unknown) => (env as Record<symbol, EnvMeta>)[ENV_META];

describe("the go env package", () => {
  // the generated file compiled against the real framework, and read the
  // way an app reads it
  test("compiles and reads every kind of declaration", () => {
    const source = goEnvSource(serverSpecs([metaOf(defineEnv(schema as never, {}))]))!;
    const dir = mkdtempSync(join(tmpdir(), "borgo-envgo-"));
    writeFileSync(
      join(dir, "go.mod"),
      ["module envapp", "", "go 1.27.0", "", "require github.com/LuigiDavideMicca/borgo v0.0.0", "", `replace github.com/LuigiDavideMicca/borgo => ${repo}`, ""].join("\n"),
    );
    mkdirSync(join(dir, "env"));
    writeFileSync(join(dir, "env", "env.gen.go"), source);
    writeFileSync(
      join(dir, "env", "env_test.go"),
      `package env

import (
	"math"
	"strings"
	"testing"
)

func TestLoad(t *testing.T) {
	t.Setenv("DATABASE_URL", "postgres://u@h/db")
	t.Setenv("DEBUG", "t")
	t.Setenv("SMTP_PORT", " 2525 ")
	s, err := Load()
	if err != nil {
		t.Fatal(err)
	}
	if s.DB_PATH != "app.db" || s.TIMEOUT_MS != 30000 || s.RATIO != 0.5 || s.VERBOSE || s.SMTP_PORT != 2525 || s.DATABASE_URL != "postgres://u@h/db" || s.TOKEN != "dev-token" {
		t.Errorf("%+v", s)
	}
	if s.MARKED != "a"+string(rune(0xfeff))+"b" || !math.Signbit(s.NEG_ZERO) {
		t.Errorf("marked %q, -0 read as %v", s.MARKED, s.NEG_ZERO)
	}
	if s.DEBUG == nil || !*s.DEBUG || s.SECRET != nil || s.NAME != nil {
		t.Errorf("optionals: %v %v %v", s.DEBUG, s.SECRET, s.NAME)
	}
	t.Setenv("SECRET", " raw ")
	t.Setenv("NAME", "n")
	if s, err := Load(); err != nil || *s.SECRET != " raw " || *s.NAME != "n" {
		t.Errorf("set optionals: %v %v", s, err)
	}
	t.Setenv("DATABASE_URL", "")
	t.Setenv("TIMEOUT_MS", "soon")
	_, err = Load()
	if err == nil || !strings.Contains(err.Error(), "2 variables refused") || !strings.Contains(err.Error(), "TIMEOUT_MS: expected a number, got \\"soon\\"") || !strings.Contains(err.Error(), "DATABASE_URL: missing (expected a url)") {
		t.Errorf("%v", err)
	}
}
`,
    );
    const tidy = Bun.spawnSync(["go", "mod", "tidy"], { cwd: dir, stderr: "pipe" });
    expect(tidy.exitCode, tidy.stderr.toString()).toBe(0);
    const vet = Bun.spawnSync(["go", "vet", "./..."], { cwd: dir, stderr: "pipe" });
    expect(vet.exitCode, vet.stderr.toString()).toBe(0);
    const run = Bun.spawnSync(["go", "test", "-count=1", "./..."], { cwd: dir, stdout: "pipe", stderr: "pipe" });
    expect(run.exitCode, run.stdout.toString() + run.stderr.toString()).toBe(0);
  });

  test("the fields say what each variable is", () => {
    const source = goEnvSource(serverSpecs([metaOf(defineEnv(schema as never, {}))]))!;
    expect(source.startsWith("// Code generated by borgo from env.ts. DO NOT EDIT.")).toBe(true);
    for (const line of [
      "\t// a string, default \"app.db\"\n\tDB_PATH string",
      "\t// a number, default 30000\n\tTIMEOUT_MS float64",
      "\t// a boolean, optional: nil when unset\n\tDEBUG *bool",
      "\t// a port, default 587\n\tSMTP_PORT int",
      "\t// checked by its validator in env.ts, optional: nil when unset\n\tSECRET *string",
      // a default makes an optional one always set; a validator makes any type the raw string
      "\t// a string, default \"info\"\n\tLEVEL string",
      "\tDOUBLED *string",
      '\t{Name: "TIMEOUT_MS", Type: "number", Default: float64(30000)},',
      '\t{Name: "TOKEN", Type: "string", Default: "dev-token", Validated: true},',
    ]) {
      expect(source).toContain(line);
    }
    // client variables are the browser's, never the go side's
    expect(source).not.toContain("BORGO_PUBLIC_TITLE");
  });

  // env.ts may export more than one schema: every one of them is read
  test("every exported schema's server variables are in the package", () => {
    const a = metaOf(defineEnv({ server: { A_ONE: {} } }, { A_ONE: "1" }));
    const b = metaOf(defineEnv({ server: { B_TWO: { type: "port", default: 1 } } }, {}));
    expect(serverSpecs([a, b]).map(([name]) => name)).toEqual(["A_ONE", "B_TWO"]);
  });

  // found by the verifier of phase 6: each of these wrote go that did not compile
  test("what the go package could not hold is refused by name", () => {
    const spec = { type: "string", optional: false, validated: false } as const;
    const a = metaOf(defineEnv({ server: { SAME: {} } }, { SAME: "1" }));
    const b = metaOf(defineEnv({ server: { SAME: { type: "port", default: 5 } } }, {}));
    expect(() => serverSpecs([a, b])).toThrow("server variable SAME is declared by more than one exported schema");
    expect(() => goEnvSource([["LONE", { ...spec, default: "x" + String.fromCharCode(0xd800) + "y" }]])).toThrow(
      "the default of LONE holds a lone surrogate",
    );
    expect(goEnvSource([["PAIR", { ...spec, default: "x😀y" }]])).toContain('Default: "x😀y"');
    expect(() => goEnvSource([["WHAT", { type: "int" as never, optional: true, validated: false }]])).toThrow(
      'server variable WHAT has type "int"',
    );
    expect(() => goEnvSource([["Db-Path", spec]])).toThrow("in capitals (DB_PATH)");
    expect(() => goEnvSource([["9lives", spec]])).toThrow("in capitals (X9LIVES)");
  });

  test("no server variable, no package; a name go cannot hold is refused by name", () => {
    expect(goEnvSource(serverSpecs([metaOf(defineEnv({ client: { BORGO_PUBLIC_A: { default: "a" } } }, {}))]))).toBeNull();
    expect(() => goEnvSource([["db_path", { type: "string", optional: false, validated: false }]])).toThrow(
      "server variable db_path cannot be a field of the go env package",
    );
  });
});

describe("writeGoEnv", () => {
  const app = (envTs: string, goMod = true) => {
    const dir = mkdtempSync(join(tmpdir(), "borgo-envgo-app-"));
    if (goMod) writeFileSync(join(dir, "go.mod"), "module app\n");
    writeFileSync(join(dir, "env.ts"), envTs);
    return dir;
  };
  const withServer = `export const env = { [Symbol.for("borgo.env")]: { failures: [], clientFailures: [], clientNames: [], clientValues: {}, serverSpecs: { DB_PATH: { type: "string", optional: false, default: "a.db", validated: false } } } };`;
  const without = `export const env = { [Symbol.for("borgo.env")]: { failures: [], clientFailures: [], clientNames: [], clientValues: {}, serverSpecs: {} } };`;

  test("writes the package, leaves an unchanged one untouched, removes one no longer declared", async () => {
    const dir = app(withServer);
    const file = join(dir, "env", "env.gen.go");
    await writeGoEnv(dir, { fresh: true });
    expect(readFileSync(file, "utf8")).toContain("DB_PATH string");
    const old = new Date(Date.now() - 3_600_000);
    utimesSync(file, old, old);
    await writeGoEnv(dir, { fresh: true });
    expect(statSync(file).mtimeMs).toBe(old.getTime());
    writeFileSync(join(dir, "env.ts"), without);
    await writeGoEnv(dir, { fresh: true });
    expect(existsSync(file)).toBe(false);
  });

  // env/ is the generated package's: a file of the app's own there breaks
  // the go build the moment the package appears (found by the verifier of
  // phase 6), so the build says so first. A test file of package env is fine
  test("refuses an env/ that holds the app's own go files, or is a file", async () => {
    const dir = app(withServer);
    mkdirSync(join(dir, "env"));
    writeFileSync(join(dir, "env", "env_test.go"), "package env");
    await writeGoEnv(dir, { fresh: true });
    writeFileSync(join(dir, "env", "own.go"), "package settings");
    await expect(writeGoEnv(dir, { fresh: true })).rejects.toThrow("it holds own.go - move it to a package of its own");
    const fileDir = app(withServer);
    writeFileSync(join(fileDir, "env"), "x");
    await expect(writeGoEnv(fileDir, { fresh: true })).rejects.toThrow("env is a file");
  });

  // an app upgraded from 0.2x with an env/ package of its own and no server
  // variable in env.ts has nothing generated, so nothing to refuse
  test("leaves an env/ of the app's own alone when there is nothing to write", async () => {
    const dir = app(without);
    mkdirSync(join(dir, "env"));
    writeFileSync(join(dir, "env", "settings.go"), "package settings");
    await writeGoEnv(dir, { fresh: true });
    expect(readFileSync(join(dir, "env", "settings.go"), "utf8")).toBe("package settings");
    const file = app(without);
    writeFileSync(join(file, "env"), "x");
    await writeGoEnv(file, { fresh: true });
  });

  test("never removes a file of the app's own, and does nothing without go.mod", async () => {
    const dir = app(without);
    mkdirSync(join(dir, "env"));
    writeFileSync(join(dir, "env", "env.gen.go"), "package env // mine\n");
    await writeGoEnv(dir, { fresh: true });
    expect(readFileSync(join(dir, "env", "env.gen.go"), "utf8")).toBe("package env // mine\n");
    const noGo = app(withServer, false);
    await writeGoEnv(noGo, { fresh: true });
    expect(existsSync(join(noGo, "env"))).toBe(false);
  });
});

// the build's own code generation writes the package: a run that stopped
// calling writeGoEnv left every committed file in place and every diff
// clean (found by the verifier of phase 6)
test("runBorgogen writes the go env package before anything else", async () => {
  const { runBorgogen } = await import("../src/util");
  const dir = mkdtempSync(join(tmpdir(), "borgo-envgo-run-"));
  writeFileSync(join(dir, "go.mod"), "module app\n");
  writeFileSync(
    join(dir, "env.ts"),
    `export const env = { [Symbol.for("borgo.env")]: { failures: [], clientFailures: [], clientNames: [], clientValues: {}, serverSpecs: { DB_PATH: { type: "string", optional: false, default: "a.db", validated: false } } } };`,
  );
  const cwd = process.cwd();
  process.chdir(dir);
  try {
    expect(await runBorgogen({ fresh: true })).toBe(true);
  } finally {
    process.chdir(cwd);
  }
  expect(readFileSync(join(dir, "env", "env.gen.go"), "utf8")).toContain("DB_PATH string");
});
