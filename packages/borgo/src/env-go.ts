// the go half of the app-env story: env/env.gen.go, written from env.ts by
// the build and the dev loop, so the process that opens the database reads
// the same contract as the one that boots the render service - piazza's F4,
// "the typed environment covers half the app"
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { EnvMeta, ServerSpec } from "./env";
import { appEnvMetas } from "./env-app";

export const GO_ENV_DIR = "env";
export const GO_ENV_FILE = "env.gen.go";
const HEADER = "// Code generated by borgo from env.ts. DO NOT EDIT.";

const goTypes: Record<ServerSpec["type"], string> = {
  string: "string",
  url: "string",
  number: "float64",
  boolean: "bool",
  port: "int",
};

// the go type a variable reads as: a validate spec is the raw string, an
// optional one without a default may be absent and is a pointer
function goType(name: string, spec: ServerSpec): string {
  if (!spec.validated && !Object.hasOwn(goTypes, spec.type)) {
    // only an env.ts in plain javascript gets here: the types refuse it
    throw new Error(`borgo env: server variable ${name} has type ${JSON.stringify(spec.type)}, which is none of string, number, boolean, url or port`);
  }
  const base = spec.validated ? "string" : goTypes[spec.type];
  return spec.optional && spec.default === undefined ? `*${base}` : base;
}

// json's string syntax is go's: the same escapes, and U+2028 is legal in both.
// a validate spec's default is always the raw string (env.ts refuses others)
function goLiteral(name: string, spec: ServerSpec, value: string | number | boolean): string {
  if (typeof value === "string") {
    // a lone surrogate is a string javascript holds and go cannot, and a
    // byte order mark is refused by the go compiler inside a source file
    if (/\p{Surrogate}/u.test(value)) {
      throw new Error(`borgo env: the default of ${name} holds a lone surrogate, which no go string can hold`);
    }
    return JSON.stringify(value).replaceAll("\ufeff", "\\ufeff");
  }
  if (typeof value === "boolean") return String(value);
  if (spec.type === "number") {
    // json writes -0 as 0
    return Object.is(value, -0) ? "math.Copysign(0, -1)" : `float64(${JSON.stringify(value)})`;
  }
  return JSON.stringify(value);
}

function describe(spec: ServerSpec): string {
  const what = spec.validated ? "checked by its validator in env.ts" : `a ${spec.type}`;
  if (spec.default !== undefined) return `${what}, default ${JSON.stringify(spec.default).replaceAll("\ufeff", "\\ufeff")}`;
  return spec.optional ? `${what}, optional: nil when unset` : what;
}

// every schema's server variables, in the order env.ts declares them
// (a name declared by two exported schemas is refused: the go package would
// hold it twice, and nothing could say which one the app meant)
export function serverSpecs(metas: EnvMeta[]): [string, ServerSpec][] {
  const specs = metas.flatMap((meta) => Object.entries(meta.serverSpecs ?? {}));
  const seen = new Set<string>();
  for (const [name] of specs) {
    if (seen.has(name)) {
      throw new Error(`borgo env: server variable ${name} is declared by more than one exported schema - one variable, one source of truth`);
    }
    seen.add(name);
  }
  return specs;
}

// the source of env/env.gen.go, or null when env.ts declares no server
// variable. A name go cannot hold as an exported field is refused by name
export function goEnvSource(specs: [string, ServerSpec][]): string | null {
  if (specs.length === 0) return null;
  for (const [name] of specs) {
    if (!/^[A-Z][A-Za-z0-9_]*$/.test(name)) {
      throw new Error(
        `borgo env: server variable ${name} cannot be a field of the go env package - name it as environment variables usually are, in capitals (${name.toUpperCase().replace(/[^A-Z0-9_]/g, "_").replace(/^[^A-Z]/, "X$&")})`,
      );
    }
  }
  const needsMath = specs.some(([, spec]) => Object.is(spec.default, -0));
  const fields = specs.map(([name, spec]) => `\t// ${describe(spec)}\n\t${name} ${goType(name, spec)}`);
  const vars = specs.map(([name, spec]) => {
    const parts = [`Name: ${JSON.stringify(name)}`, `Type: ${JSON.stringify(spec.type)}`];
    if (spec.optional) parts.push("Optional: true");
    if (spec.default !== undefined) parts.push(`Default: ${goLiteral(name, spec, spec.default)}`);
    if (spec.validated) parts.push("Validated: true");
    return `\t{${parts.join(", ")}},`;
  });
  const assigns = specs.map(([name, spec]) => {
    const t = goType(name, spec);
    if (t.startsWith("*")) {
      return `\tif x, ok := v[${JSON.stringify(name)}].(${t.slice(1)}); ok {\n\t\ts.${name} = &x\n\t}`;
    }
    return `\ts.${name} = v[${JSON.stringify(name)}].(${t})`;
  });
  return [
    HEADER,
    "",
    "// Package env is the app's server environment as env.ts declares it, read",
    "// with the same rules and refused in the same words. env.ts is the source:",
    "// borgo build and borgo dev write this file again from it.",
    "package env",
    "",
    "import (",
    '\t"fmt"',
    ...(needsMath ? ['\t"math"'] : []),
    '\t"os"',
    "",
    '\t"github.com/LuigiDavideMicca/borgo"',
    ")",
    "",
    "// Server holds the server variables of env.ts.",
    "type Server struct {",
    fields.join("\n\n"),
    "}",
    "",
    "var vars = []borgo.EnvVar{",
    ...vars,
    "}",
    "",
    "// Load reads the variables, every refusal named.",
    "func Load() (Server, error) {",
    "\tv, err := borgo.ReadEnv(vars)",
    "\tif err != nil {",
    "\t\treturn Server{}, err",
    "\t}",
    "\tvar s Server",
    ...assigns,
    "\treturn s, nil",
    "}",
    "",
    "// Must is Load for main and package init: a refused environment ends the",
    "// process with the refusal, as the render service's boot check does.",
    "func Must() Server {",
    "\ts, err := Load()",
    "\tif err != nil {",
    "\t\tfmt.Fprintln(os.Stderr, err)",
    "\t\tos.Exit(1)",
    "\t}",
    "\treturn s",
    "}",
    "",
  ].join("\n");
}

// writes env/env.gen.go when its text changed - an untouched mtime keeps the
// go build cache warm - and removes one of ours when env.ts no longer
// declares a server variable. A go app only: without go.mod there is no go
// side to give it to
export async function writeGoEnv(root = process.cwd(), { fresh = false }: { fresh?: boolean } = {}): Promise<void> {
  if (!existsSync(join(root, "go.mod"))) return;
  const dir = join(root, GO_ENV_DIR);
  const file = join(dir, GO_ENV_FILE);
  const source = goEnvSource(serverSpecs((await appEnvMetas(root, { fresh })).metas));
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (source === null) {
    if (current?.startsWith(HEADER)) rmSync(file);
    return;
  }
  // env/ is where the generated package lives: a file there of the app's
  // own would share its package, or be another package in its directory,
  // and break the go build (found by the verifier of phase 6). Asked only
  // when there is a package to write: an app with an env/ of its own and no
  // server variable never meets it (found writing the 0.30 migration guide)
  if (existsSync(dir)) {
    if (!statSync(dir).isDirectory()) {
      throw new Error(`borgo env: ${GO_ENV_DIR} is a file, and it is where the go side of env.ts is written - rename it`);
    }
    const own = readdirSync(dir).filter((name) => name.endsWith(".go") && name !== GO_ENV_FILE && !name.endsWith("_test.go"));
    if (own.length > 0) {
      throw new Error(
        `borgo env: ${GO_ENV_DIR}/ is where the go side of env.ts is written, and it holds ${own.join(", ")} - move ${own.length === 1 ? "it" : "them"} to a package of ${own.length === 1 ? "its" : "their"} own`,
      );
    }
  }
  if (current === source) return;
  mkdirSync(dir, { recursive: true });
  writeFileSync(file, source);
}
