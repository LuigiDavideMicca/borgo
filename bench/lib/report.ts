import { environmentMarkdown, type Environment } from "./env";
import { rsd } from "./stats";
import { SCENARIOS } from "./scenarios";
import type { AppResult, ScenarioId } from "./types";

export interface RunConfig {
  connections: number;
  durationSeconds: number;
  warmupSeconds: number;
  runs: number;
  memoryConnections: number;
  scenarios: ScenarioId[];
  apps: string[];
  loadArgvTemplate: string;
}

export interface Report {
  schema: 1;
  environment: Environment;
  config: RunConfig;
  results: AppResult[];
}

const fmt = (n: number, digits = 0) =>
  n.toLocaleString("en-US", { minimumFractionDigits: digits, maximumFractionDigits: digits });

const mib = (bytes: number) => (bytes / 1024 ** 2).toFixed(1);
const kib = (bytes: number) => (bytes / 1024).toFixed(1);

export function reportMarkdown(report: Report): string {
  const lines: string[] = [];
  const { config, results } = report;

  lines.push("# borgo benchmark run");
  lines.push("");
  lines.push(
    "Generated by `bench/run.ts`. Read [bench/README.md](../README.md) before reading any number " +
      "here: it states the method, what is deliberately not measured, and who wrote the harness.",
  );
  lines.push("");
  lines.push("## Environment");
  lines.push("");
  lines.push(environmentMarkdown(report.environment));
  lines.push("");
  lines.push("## Method for this run");
  lines.push("");
  lines.push("| setting | value |");
  lines.push("| --- | --- |");
  lines.push(`| connections | ${config.connections} |`);
  lines.push(`| duration per run | ${config.durationSeconds}s |`);
  lines.push(`| warmup (discarded) | ${config.warmupSeconds}s |`);
  lines.push(`| runs per scenario | ${config.runs} (**median reported**, not best) |`);
  lines.push(`| connections held for the memory probe | ${config.memoryConnections} |`);
  lines.push(`| load invocation | \`${config.loadArgvTemplate}\` |`);
  lines.push("");

  const implemented = results.filter((r) => r.status !== "stub");
  const stubs = results.filter((r) => r.status === "stub");

  lines.push("## Startup");
  lines.push("");
  lines.push("| app | time to first successful response | RSS after boot |");
  lines.push("| --- | ---: | ---: |");
  for (const app of implemented) {
    if (!app.startup) {
      lines.push(`| ${app.app} | did not start | - |`);
      continue;
    }
    lines.push(
      `| ${app.app} | ${fmt(app.startup.timeToFirstResponseMs)} ms | ${mib(app.startup.bootRssBytes)} MiB |`,
    );
  }
  lines.push("");

  for (const scenario of SCENARIOS.filter((s) => config.scenarios.includes(s.id))) {
    const rows = implemented
      .map((app) => ({ app, result: app.scenarios.find((s) => s.scenario === scenario.id) }))
      .filter((r) => r.result);
    if (rows.length === 0) continue;

    lines.push(`## ${scenario.title}  \`GET ${scenario.path}\``);
    lines.push("");
    lines.push(scenario.description);
    lines.push("");

    if (scenario.kind === "load") {
      lines.push("| app | req/s (median) | p50 | p90 | p99 | success | run-to-run RSD | non-2xx |");
      lines.push("| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |");
      for (const { app, result } of rows) {
        if (result!.status !== "ok" || !result!.load) {
          lines.push(`| ${app.app} | ${result!.status}: ${result!.reason ?? "-"} | | | | | | |`);
          continue;
        }
        const m = result!.load.median;
        const noise = rsd(result!.load.runs.map((r) => r.requestsPerSec));
        const bad = Object.entries(m.statusCodes)
          .filter(([code]) => !code.startsWith("2") && code !== "2xx")
          .map(([code, count]) => `${code}:${count}`)
          .join(" ");
        lines.push(
          `| ${app.app} | ${fmt(m.requestsPerSec)} | ${m.latencyMs.p50.toFixed(2)} ms | ` +
            `${m.latencyMs.p90.toFixed(2)} ms | ${m.latencyMs.p99.toFixed(2)} ms | ` +
            `${(m.successRate * 100).toFixed(1)}% | ${noise.toFixed(1)}% | ${bad || "none"} |`,
        );
      }
      lines.push("");
      lines.push("<details><summary>individual runs</summary>");
      lines.push("");
      lines.push("| app | run | req/s |");
      lines.push("| --- | ---: | ---: |");
      for (const { app, result } of rows) {
        result!.load?.runs.forEach((r, i) => lines.push(`| ${app.app} | ${i + 1} | ${fmt(r.requestsPerSec)} |`));
      }
      lines.push("");
      lines.push("</details>");
      lines.push("");
    } else {
      lines.push("| app | RSS idle | RSS holding N | connections held | delta | **per connection** | trustworthy |");
      lines.push("| --- | ---: | ---: | ---: | ---: | ---: | :-: |");
      for (const { app, result } of rows) {
        if (result!.status !== "ok" || !result!.memory) {
          lines.push(`| ${app.app} | ${result!.status}: ${result!.reason ?? "-"} | | | | | |`);
          continue;
        }
        const m = result!.memory;
        lines.push(
          `| ${app.app} | ${mib(m.idleRssBytes)} MiB | ${mib(m.loadedRssBytes)} MiB | ` +
            `${m.established} | ${mib(m.deltaBytes)} MiB | **${kib(m.bytesPerConnection)} kiB** | ` +
            `${m.reliable ? "yes" : "**no**"} |`,
        );
      }
      lines.push("");

      const caveats = rows.flatMap(({ app, result }) =>
        (result!.memory?.notes ?? []).map((note) => `- **${app.app}**: ${note}`),
      );
      if (caveats.length > 0) {
        lines.push("Caveats reported by the probe itself:");
        lines.push("");
        lines.push(...caveats);
        lines.push("");
      }
      lines.push(
        "RSS is the resident set of the *whole process tree* (for borgo: the Bun front server " +
          "plus the Go API binary). Absolute RSS says more about an allocator's growth policy " +
          "than about a framework; the delta per connection is the comparable figure, and even " +
          "it is a lower bound, since neither runtime returns freed pages to the OS promptly.",
      );
      lines.push("");
      lines.push("<details><summary>per-process breakdown while holding connections</summary>");
      lines.push("");
      lines.push("| app | pid | process | RSS |");
      lines.push("| --- | ---: | --- | ---: |");
      for (const { app, result } of rows) {
        for (const p of result!.memory?.processes ?? []) {
          lines.push(`| ${app.app} | ${p.pid} | ${p.command} | ${mib(p.rssBytes)} MiB |`);
        }
      }
      lines.push("");
      lines.push("</details>");
      lines.push("");
    }
  }

  if (stubs.length > 0) {
    lines.push("## Not measured");
    lines.push("");
    lines.push(
      "These implementations exist as a directory and a manifest but were not run. They are " +
        "listed rather than omitted, because a missing competitor is information too.",
    );
    lines.push("");
    lines.push("| app | framework | why not |");
    lines.push("| --- | --- | --- |");
    for (const app of stubs) {
      lines.push(`| ${app.app} | ${app.manifest.framework} | ${app.manifest.todo ?? "unspecified"} |`);
    }
    lines.push("");
  }

  const failures = implemented.filter((r) => r.status === "failed");
  if (failures.length > 0) {
    lines.push("## Failures");
    lines.push("");
    for (const app of failures) lines.push(`- **${app.app}**: ${app.reason ?? "unknown"}`);
    lines.push("");
  }

  return lines.join("\n") + "\n";
}
